#!/usr/bin/env python3
"""tools/strings.tsv (key, zh, en) -> res/values (zh, default), res/values-zh (zh), res/values-en (en)."""
import io, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for n, line in enumerate(io.open(os.path.join(root, 'tools', 'strings.tsv'), encoding='utf-8'), 1):
    line = line.rstrip('\n')
    if not line or line.startswith('#'):
        continue
    parts = line.split('\t')
    if len(parts) != 3:
        sys.exit('strings.tsv:%d: need 3 tab-separated fields, got %d' % (n, len(parts)))
    rows.append(parts)
keys = [r[0] for r in rows]
dup = sorted({k for k in keys if keys.count(k) > 1})
if dup:
    sys.exit('duplicate keys: ' + ', '.join(dup))

def esc(s):
    s = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    return s.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n')

def write(folder, col):
    d = os.path.join(root, 'app', 'src', 'main', 'res', folder)
    os.makedirs(d, exist_ok=True)
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- generated by tools/gen_strings.py from tools/strings.tsv; edit the TSV -->', '<resources>']
    for r in rows:
        fmt = '' if '%1$' in r[col] else ' formatted="false"'
        out.append('    <string name="%s"%s>%s</string>' % (r[0], fmt, esc(r[col])))
    out.append('</resources>')
    io.open(os.path.join(d, 'strings.xml'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')

write('values', 1); write('values-zh', 1); write('values-en', 2)
print('strings: %d keys' % len(rows))
